/**
 * Cartografía propia de Colombia (sin teselas externas).
 *
 * La silueta es la **disolución** de los 33 polígonos departamentales de
 * `backend/app/data/colombia_departamentos.geojson` (DANE, MGN 2018): se
 * recogen las aristas que aparecen una sola vez entre departamentos y se
 * encadenan en anillos; así el país queda sin líneas internas y con el
 * archipiélago de San Andrés incluido. No se inventan coordenadas ni se
 * recortan islas.
 *
 * La máscara inversa es un anillo que cubre el mundo con un hueco por cada
 * anillo del país: lo que queda fuera se atenúa. deck.gl la dibuja debajo de
 * los datos (igual con mapa base que sin él).
 *
 * Los estilos `public/mapa-colombia-*.json` solo pintan el mar y declaran la
 * atribución: no piden teselas ni fuentes externas.
 */

/** Anillo cerrado en [longitud, latitud]. */
export type Ring = [number, number][];

/**
 * Límites de la cámara. El centro no sale de aquí, así que no se llega a
 * «otra copia del mundo» ni a otros continentes. El país entero (incluido el
 * archipiélago) cabe con margen; la máscara se encarga de lo de fuera.
 */
export const MAPA_LIMITES: [[number, number], [number, number]] = [
  [-82.6, -5.2],
  [-66.2, 13.8],
];

/** Zoom: por debajo de 3,4 el país deja de leerse; por encima de 9 no hay más detalle que mostrar. */
export const MAPA_ZOOM = { min: 3.4, max: 9 } as const;

/** Inclinación: 0 (plano) a 60°. El diseño usa 45–50° y en calidad liviana, 0. */
export const MAPA_INCLINACION = { min: 0, max: 60 } as const;

/** Giro: el norte no se pierde. El encuadre usa −10° y la ruta −12°. */
export const MAPA_GIRO = { min: -40, max: 40 } as const;

/** Caja holgada para descartar datos que no son de Colombia (no recorta trazados que cruzan el borde). */
export const MAPA_FILTRO: [[number, number], [number, number]] = [
  [-84, -6],
  [-64, 15.5],
];

/** ¿La coordenada cae en la caja de Colombia? Se usa como filtro de datos, no como recorte. */
export function dentroDeColombia([lng, lat]: readonly number[]): boolean {
  return lng >= MAPA_FILTRO[0][0] && lng <= MAPA_FILTRO[1][0] && lat >= MAPA_FILTRO[0][1] && lat <= MAPA_FILTRO[1][1];
}

